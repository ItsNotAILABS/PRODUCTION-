/**
 * PROTO-INFRA-001: Infrastructure Code Generation Protocol
 * ═══════════════════════════════════════════════════════════════════
 *
 * Generates deployment manifests, IaC definitions, and configuration
 * for the sovereign multi-cloud fleet. Targets:
 *   - Cloudflare Workers (wrangler.toml)
 *   - ICP Canisters (dfx.json + Motoko scaffold)
 *   - Terraform HCL (AWS Lambda, GCP Cloud Run, Azure Functions)
 *   - Docker Compose (bare-metal / on-prem)
 *   - GitHub Actions CI (sovereign build-test-land pipeline)
 *
 * All generated configs embed the organism's phi-constants as environment
 * variables so every deployed unit is phi-aware at runtime.
 */

'use strict';

const PHI           = 1.618033988749895;
const PHI_INV       = 0.618033988749895;
const HEARTBEAT_MS  = 873;

const TARGET = Object.freeze({
  CLOUDFLARE: 'cloudflare',
  ICP:        'icp',
  TERRAFORM:  'terraform',
  COMPOSE:    'compose',
  GITHUB_CI:  'github_ci',
});

/**
 * Generate a wrangler.toml for a Cloudflare Worker.
 */
function wranglerToml({ name, accountId = '', mainFile = 'src/index.js', vars = {}, cronSchedule = null }) {
  const allVars = { PHI: String(PHI), HEARTBEAT_MS: String(HEARTBEAT_MS), ...vars };
  const varLines = Object.entries(allVars).map(([k,v]) => `${k} = "${v}"`);
  const lines = [
    `name = "${name.toLowerCase().replace(/[^a-z0-9-]/g, '-')}"`,
    `main = "${mainFile}"`,
    `compatibility_date = "${new Date().toISOString().slice(0,10)}"`,
    accountId ? `account_id = "${accountId}"` : '',
    '',
    '[vars]',
    ...varLines,
  ];
  if (cronSchedule) {
    lines.push('', '[[triggers]]', `crons = ["${cronSchedule}"]`);
  }
  return lines.filter(l => l !== undefined).join('\n');
}

/**
 * Generate a dfx.json canister entry + Motoko stub.
 */
function icpConfig({ canisterId, name, network = 'ic', mainFile = 'src/main.mo', memory = 256 }) {
  const dfxJson = {
    version: 1,
    canisters: {
      [name]: {
        type: 'motoko',
        main: mainFile,
        candid: `src/${name}.did`,
      },
    },
    networks: {
      [network]: {
        providers: [network === 'ic' ? 'https://ic0.app' : 'http://127.0.0.1:8000'],
        type: network === 'ic' ? 'persistent' : 'ephemeral',
      },
    },
  };

  const motokoStub = [
    `// ${name} — ICP Canister`,
    `// Generated by infrastructure-codegen-protocol`,
    `import Time "mo:base/Time";`,
    ``,
    `actor ${name} {`,
    `  let PHI : Float = ${PHI};`,
    `  let HEARTBEAT_MS : Nat = ${HEARTBEAT_MS};`,
    ``,
    `  stable var beat : Nat = 0;`,
    ``,
    `  public func pulse() : async Nat {`,
    `    beat += 1;`,
    `    beat`,
    `  };`,
    ``,
    `  public query func status() : async Text {`,
    `    "sovereign"`,
    `  };`,
    `};`,
  ].join('\n');

  return { dfxJson: JSON.stringify(dfxJson, null, 2), motokoStub };
}

/**
 * Generate Terraform HCL for a Lambda function.
 */
function terraformLambda({ name, region = 'us-east-1', runtime = 'nodejs20.x', handler = 'index.handler', envVars = {} }) {
  const allEnv = { PHI: String(PHI), HEARTBEAT_MS: String(HEARTBEAT_MS), ...envVars };
  const envBlock = Object.entries(allEnv).map(([k, v]) => `      ${k} = "${v}"`).join('\n');
  return [
    `resource "aws_lambda_function" "${name}" {`,
    `  function_name = "${name}"`,
    `  runtime       = "${runtime}"`,
    `  handler       = "${handler}"`,
    `  role          = aws_iam_role.lambda_exec.arn`,
    `  filename      = "dist/${name}.zip"`,
    ``,
    `  environment {`,
    `    variables = {`,
    envBlock,
    `    }`,
    `  }`,
    ``,
    `  tags = {`,
    `    Organism    = "sovereign"`,
    `    PhiScore    = "1.0"`,
    `  }`,
    `}`,
  ].join('\n');
}

/**
 * Generate a Docker Compose service definition.
 */
function composeService({ name, image, port = 8080, envVars = {}, restart = 'unless-stopped' }) {
  const allEnv = { PHI: String(PHI), HEARTBEAT_MS: String(HEARTBEAT_MS), ...envVars };
  return {
    [name]: {
      image,
      restart,
      ports: [`"${port}:${port}"`],
      environment: allEnv,
      labels: { 'organism.ring': 'sovereign', 'organism.phi_score': '1.0' },
    },
  };
}

/**
 * Generate a GitHub Actions workflow for sovereign CI.
 */
function githubCiWorkflow({ repoName, node = '20', branches = ['main'], protocolsPath = 'protocols/' }) {
  return [
    `name: Sovereign CI`,
    ``,
    `on:`,
    `  push:`,
    `    branches: [${branches.map(b => `"${b}"`).join(', ')}]`,
    `  pull_request:`,
    `    branches: [${branches.map(b => `"${b}"`).join(', ')}]`,
    ``,
    `jobs:`,
    `  organism-build:`,
    `    runs-on: ubuntu-latest`,
    `    steps:`,
    `      - uses: actions/checkout@v4`,
    `      - uses: actions/setup-node@v4`,
    `        with:`,
    `          node-version: "${node}"`,
    `      - name: Install deps`,
    `        run: npm ci`,
    `      - name: Validate protocols`,
    `        run: node scripts/sandcastle-pipeline.js --validate --wiring`,
    `      - name: Run sandcastle`,
    `        run: node scripts/sandcastle-pipeline.js`,
    `        env:`,
    `          PHI: "${PHI}"`,
    `          HEARTBEAT_MS: "${HEARTBEAT_MS}"`,
  ].join('\n');
}

/**
 * Generate any target type from a unified spec.
 */
function generate(target, spec) {
  switch (target) {
    case TARGET.CLOUDFLARE: return { type: target, code: wranglerToml(spec) };
    case TARGET.ICP:        return { type: target, ...icpConfig(spec) };
    case TARGET.TERRAFORM:  return { type: target, code: terraformLambda(spec) };
    case TARGET.COMPOSE:    return { type: target, code: JSON.stringify(composeService(spec), null, 2) };
    case TARGET.GITHUB_CI:  return { type: target, code: githubCiWorkflow(spec) };
    default: throw new Error(`Unknown target: ${target}`);
  }
}

module.exports = {
  generate, wranglerToml, icpConfig, terraformLambda, composeService, githubCiWorkflow,
  TARGET, PHI, PHI_INV, HEARTBEAT_MS,
};
