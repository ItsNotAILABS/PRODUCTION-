#!/usr/bin/env node
/**
 * 📬 AGENT MESSAGING — Inter-Agent Communication Protocol
 * ════════════════════════════════════════════════════════════════════════════
 *
 * Implements agent-to-agent messaging via GitHub Issues labels.
 * Agents communicate by creating issues with special labels that route
 * messages to target agents.
 *
 * Message Protocol:
 *   Label format: agent-msg:{sender}:{target}:{type}
 *   Types: request, response, broadcast, escalation
 *
 * Usage:
 *   node sdk/agents/bootstrap/agent-messaging.js --send --from=bot-a --to=bot-b --type=request
 *   node sdk/agents/bootstrap/agent-messaging.js --receive --agent=bot-a
 *   node sdk/agents/bootstrap/agent-messaging.js --broadcast --from=alpha --message="Fleet update"
 *
 * id: atlas://sdk/agent-messaging
 */

'use strict';

const fs   = require('fs');
const path = require('path');

const PHI     = 1.618033988749895;
const PHI_INV = 1 / PHI;

const REPO       = path.resolve(__dirname, '../../..');
const MSG_DIR    = path.join(REPO, 'dist', 'agent-messages');
const QUEUE_FILE = path.join(MSG_DIR, 'message-queue.jsonl');

// ── Parse Arguments ───────────────────────────────────────────────────────────
const args = {
  send: process.argv.includes('--send'),
  receive: process.argv.includes('--receive'),
  broadcast: process.argv.includes('--broadcast'),
  from: process.argv.find(a => a.startsWith('--from='))?.split('=')[1],
  to: process.argv.find(a => a.startsWith('--to='))?.split('=')[1],
  agent: process.argv.find(a => a.startsWith('--agent='))?.split('=')[1],
  type: process.argv.find(a => a.startsWith('--type='))?.split('=')[1] || 'request',
  message: process.argv.find(a => a.startsWith('--message='))?.split('=')[1],
  priority: process.argv.find(a => a.startsWith('--priority='))?.split('=')[1] || 'normal',
};

// ── Message Types ─────────────────────────────────────────────────────────────
const MESSAGE_TYPES = {
  request: {
    label: 'agent-request',
    priority: 1,
    requiresResponse: true,
  },
  response: {
    label: 'agent-response',
    priority: 2,
    requiresResponse: false,
  },
  broadcast: {
    label: 'agent-broadcast',
    priority: 3,
    requiresResponse: false,
  },
  escalation: {
    label: 'agent-escalation',
    priority: 0,  // Highest priority
    requiresResponse: true,
  },
  coordination: {
    label: 'agent-coordination',
    priority: 1,
    requiresResponse: true,
  },
  heartbeat: {
    label: 'agent-heartbeat',
    priority: 4,
    requiresResponse: false,
  },
};

// ── Priority Levels ───────────────────────────────────────────────────────────
const PRIORITIES = {
  critical: 0,
  high: 1,
  normal: 2,
  low: 3,
};

// ── Create Message ────────────────────────────────────────────────────────────
function createMessage(from, to, type, content, priority = 'normal') {
  const id = `msg-${Date.now()}-${Math.random().toString(36).substr(2, 9)}`;
  
  return {
    id,
    from: from.startsWith('atlas://') ? from : `atlas://bot/${from}`,
    to: to === '*' ? 'atlas://broadcast' : (to.startsWith('atlas://') ? to : `atlas://bot/${to}`),
    type,
    content,
    priority: PRIORITIES[priority] ?? 2,
    timestamp: new Date().toISOString(),
    status: 'pending',
    labels: [
      MESSAGE_TYPES[type]?.label || 'agent-msg',
      `from:${from.replace('atlas://bot/', '')}`,
      `to:${to === '*' ? 'all' : to.replace('atlas://bot/', '')}`,
      `priority:${priority}`,
    ],
  };
}

// ── Send Message ──────────────────────────────────────────────────────────────
function sendMessage(from, to, type, content, priority) {
  console.log(`📬 Sending message...\n`);
  
  fs.mkdirSync(MSG_DIR, { recursive: true });
  
  const msg = createMessage(from, to, type, content, priority);
  
  // Append to queue
  fs.appendFileSync(QUEUE_FILE, JSON.stringify(msg) + '\n');
  
  console.log(`  ✉️ Message created: ${msg.id}`);
  console.log(`     From: ${msg.from}`);
  console.log(`     To: ${msg.to}`);
  console.log(`     Type: ${type}`);
  console.log(`     Priority: ${priority}`);
  console.log(`     Labels: ${msg.labels.join(', ')}`);
  
  // Generate GitHub Issue format
  const issueTitle = `[${type.toUpperCase()}] ${from} → ${to}: ${content?.substring(0, 50) || 'Message'}`;
  const issueBody = `
## Agent Message

**ID:** \`${msg.id}\`
**From:** \`${msg.from}\`
**To:** \`${msg.to}\`
**Type:** ${type}
**Priority:** ${priority}
**Timestamp:** ${msg.timestamp}

## Content

${content || '_No content_'}

## Labels

${msg.labels.map(l => `- \`${l}\``).join('\n')}

---
*Auto-generated by agent-messaging protocol*
`;

  // Save issue template
  const issueFile = path.join(MSG_DIR, `${msg.id}.issue.md`);
  fs.writeFileSync(issueFile, `# ${issueTitle}\n${issueBody}`);
  
  console.log(`\n  📄 Issue template saved: ${issueFile}`);
  
  return msg;
}

// ── Receive Messages ──────────────────────────────────────────────────────────
function receiveMessages(agentId) {
  console.log(`📬 Checking messages for: ${agentId}\n`);
  
  if (!fs.existsSync(QUEUE_FILE)) {
    console.log('  📭 No messages in queue');
    return [];
  }
  
  const lines = fs.readFileSync(QUEUE_FILE, 'utf8').trim().split('\n').filter(Boolean);
  const messages = lines.map(l => {
    try { return JSON.parse(l); } catch { return null; }
  }).filter(Boolean);
  
  // Filter for this agent
  const targetUri = agentId.startsWith('atlas://') ? agentId : `atlas://bot/${agentId}`;
  const agentMessages = messages.filter(m => 
    m.to === targetUri || 
    m.to === 'atlas://broadcast' ||
    (m.status === 'pending' && m.to.includes(agentId))
  );
  
  if (agentMessages.length === 0) {
    console.log('  📭 No messages for this agent');
    return [];
  }
  
  console.log(`  📬 Found ${agentMessages.length} message(s):\n`);
  
  // Sort by priority (lower = higher priority)
  agentMessages.sort((a, b) => a.priority - b.priority);
  
  agentMessages.forEach((msg, i) => {
    console.log(`  ${i + 1}. [${msg.type}] from ${msg.from}`);
    console.log(`     Priority: ${Object.keys(PRIORITIES).find(k => PRIORITIES[k] === msg.priority)}`);
    console.log(`     Time: ${msg.timestamp}`);
    console.log(`     Content: ${msg.content?.substring(0, 60) || '_empty_'}...`);
    console.log('');
  });
  
  return agentMessages;
}

// ── Broadcast Message ─────────────────────────────────────────────────────────
function broadcastMessage(from, content, priority = 'normal') {
  console.log(`📢 Broadcasting message from ${from}...\n`);
  
  return sendMessage(from, '*', 'broadcast', content, priority);
}

// ── Generate Label String ─────────────────────────────────────────────────────
function generateLabel(from, to, type) {
  const fromId = from.replace('atlas://bot/', '').replace('organism-', '').replace('-bot', '');
  const toId = to === '*' ? 'all' : to.replace('atlas://bot/', '').replace('organism-', '').replace('-bot', '');
  return `agent-msg:${fromId}:${toId}:${type}`;
}

// ── Main ──────────────────────────────────────────────────────────────────────
if (args.send && args.from && args.to) {
  sendMessage(args.from, args.to, args.type, args.message, args.priority);
} else if (args.receive && args.agent) {
  receiveMessages(args.agent);
} else if (args.broadcast && args.from) {
  broadcastMessage(args.from, args.message, args.priority);
} else {
  console.log(`
📬 Agent Messaging Protocol

Usage:
  --send              Send a message
    --from=<agent>    Sender agent ID
    --to=<agent>      Target agent ID
    --type=<type>     Message type (request|response|broadcast|escalation|coordination)
    --message=<msg>   Message content
    --priority=<pri>  Priority (critical|high|normal|low)

  --receive           Receive messages
    --agent=<agent>   Agent ID to check messages for

  --broadcast         Send to all agents
    --from=<agent>    Sender agent ID
    --message=<msg>   Broadcast content

Examples:
  node agent-messaging.js --send --from=test-bot --to=alpha-bot --type=escalation --message="Help!"
  node agent-messaging.js --receive --agent=alpha-bot
  node agent-messaging.js --broadcast --from=alpha-bot --message="Fleet status update"
`);
}

module.exports = {
  MESSAGE_TYPES,
  PRIORITIES,
  createMessage,
  sendMessage,
  receiveMessages,
  broadcastMessage,
  generateLabel,
};
